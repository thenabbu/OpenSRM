#!/usr/bin/env bash
# Inline page.html into worker.src.js -> worker.js (the deployable module).
# Cloudflare Workers have no origin to fetch a stylesheet from, so the page must
# be self-contained. Run this after editing page.html.
set -euo pipefail
cd "$(dirname "$0")"

test -f page.html || { echo "page.html missing" >&2; exit 1; }
test -f worker.src.js || { echo "worker.src.js missing" >&2; exit 1; }

python3 - <<'PY'
import pathlib, sys

html = pathlib.Path('page.html').read_text()
src  = pathlib.Path('worker.src.js').read_text()

# Escape for a JS template literal.
esc = html.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')
if 'const PAGE_HTML' in src:
    sys.exit('worker.src.js already has PAGE_HTML — it should reference the injected constant only')

out = f'// GENERATED by build.sh from worker.src.js + page.html — DO NOT EDIT.\nconst PAGE_HTML = `{esc}`;\n\n{src}'
pathlib.Path('worker.js').write_text(out)
print(f'worker.js written: {len(out)} bytes (page.html {len(html)})')
PY

node --check worker.js && echo "syntax OK"

# Self-check: the generated module must actually contain the page and the
# catch-all codes. Fails loudly rather than shipping a page that renders blank.
python3 - <<'PY'
import pathlib, re, sys
out = pathlib.Path('worker.js').read_text()
html = pathlib.Path('page.html').read_text()
assert 'const PAGE_HTML' in out, 'PAGE_HTML not injected'
assert html.strip()[:40] in out.replace('\\`', '`'), 'page body not embedded'
for code in ('530', '502', '504'):
    assert re.search(rf'\b{code}\b', out), f'DEAD missing {code}'
assert 'no-store' in out, 'maintenance response is missing cache-control'
print('self-check OK')
PY
